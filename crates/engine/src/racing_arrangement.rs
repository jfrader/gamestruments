/// Build the ten-section extended tour (the six original sections plus the four
/// authored phases) without suffixing the id/title, so both the legacy Extended
/// arrangement and the `all-phases` arrangement share one section builder.
fn build_extended_sections(input: &GenerateInput) -> Result<PortableScore, String> {
    let mut score = generate_racing(input)?;
    score.sections = EXTENDED_SECTION_ORDER
        .iter()
        .map(|id| match PHASES.iter().find(|phase| phase.id == *id) {
            Some(phase) => Ok(build_phase(&score, phase)),
            None => original_section(&score, id),
        })
        .collect::<Result<Vec<_>, String>>()?;
    Ok(score)
}

fn generate_extended(input: &GenerateInput) -> Result<PortableScore, String> {
    let mut score = build_extended_sections(input)?;
    score.id.push_str(&format!("-extended-v{EXTENDED_VERSION}"));
    score.title.push_str(" — Extended");
    score.validate()?;
    Ok(score)
}

