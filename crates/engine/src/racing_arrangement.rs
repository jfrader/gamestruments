/// Version of the extended-arrangement wrapper itself. Kept independent of the
/// generator version so the suffix stays stable while the generator evolves.
pub const EXTENDED_VERSION: &str = "2";

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum RacingArrangement {
    #[default]
    Original,
    Extended,
    AllPhases,
    Seeded,
}

impl RacingArrangement {
    /// `""`/`"original"`/`"extended"` are the legacy values and stay byte-identical.
    /// `"all-phases"` is the full ten-section tour; `"seeded"` is the seeded
    /// composer (today's composed path), with `"composed"` kept as an alias.
    pub fn parse(value: &str) -> Result<Self, String> {
        match value {
            "" | "original" => Ok(Self::Original),
            "extended" => Ok(Self::Extended),
            "all-phases" => Ok(Self::AllPhases),
            "seeded" | "composed" => Ok(Self::Seeded),
            other => Err(format!("Unknown racing arrangement: {other}")),
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Original => "original",
            Self::Extended => "extended",
            Self::AllPhases => "all-phases",
            Self::Seeded => "seeded",
        }
    }
}

pub fn generate_racing_arrangement(
    input: &GenerateInput,
    arrangement: RacingArrangement,
) -> Result<PortableScore, String> {
    match arrangement {
        RacingArrangement::Original => generate_racing(input),
        RacingArrangement::Extended => generate_extended(input),
        RacingArrangement::AllPhases => generate_all_phases(input),
        RacingArrangement::Seeded => generate_seeded(input),
    }
}

/// Compose a Racing song form over the six-section pool, mirroring Suspense's
/// pool + composer: role/energy metadata (derived from the authored plans)
/// feeds a seeded composer that picks a legal order and a groove loop point,
/// and role-aware lengths re-time the sections (peaks longer, intros/outros
/// short). The six base sections are generated by [`generate_racing`] unchanged
/// at first; only their lengths, the composed surface and the score's form
/// differ.
///
/// The composed surface answers the generation traits with continuous
/// magnitude (see [`RacingTraits`]) rather than a hash re-roll, so a knob
/// turned to its extreme is clearly audible.
fn generate_seeded(input: &GenerateInput) -> Result<PortableScore, String> {
    let mut score = generate_racing(input)?;
    let bar = score.bar_ticks();
    let form_seed = racing_compose_seed(&input.secret, &input.seed);
    let traits = RacingTraits::from_input(input);
    let harmony = racing_harmony(input);
    let ceiling = racing_register_ceiling(input.style);

    // energy → tempo: the base span is widened a little on the composed path,
    // so the tempo keeps climbing to the top of the knob.
    score.bpm = (score.bpm + traits.energy_dev() * 24.0).clamp(96.0, 160.0);

    // Re-time by role before composing the form so each step references the
    // final length. Sections not chosen by the composer still re-time; they are
    // carried in the score but simply not toured. energy biases the stretch.
    for section in &mut score.sections {
        let Some(spec) = racing_phase_spec(&section.id) else {
            continue;
        };
        let bars = racing_phase_bars(&spec, form_seed, traits.energy);
        if bars * bar != section.length_ticks {
            retime_section(section, bars, bar);
        }
    }

    score.form = Some(racing_compose(form_seed));

    // The composed surface: layers breathe across blocks, joins get a seeded
    // gesture over a shared pitch class, and nothing pierces the register.
    for section in &mut score.sections {
        apply_racing_development_arc(section, bar, form_seed, traits.complexity);
    }
    apply_racing_transition_pass(&mut score, &harmony, form_seed);
    for section in &mut score.sections {
        anchor_racing_edges(section, harmony.root_pitch_class, bar);
        apply_racing_trait_surface(section, bar, &traits);
        apply_racing_register_ceiling(section, ceiling);
    }

    score.id.push_str("-seeded");
    score.title.push_str(" — Seeded");
    score.validate()?;
    Ok(score)
}

/// The continuous magnitude response of the four Racing traits (0..1), used by
/// the composed path. Each trait deviates from the neutral 0.5; the deviation
/// drives concrete parameters so a knob move changes magnitude, never a branch.
#[derive(Clone, Copy)]
struct RacingTraits {
    energy: f64,
    complexity: f64,
    #[allow(dead_code)]
    brightness: f64,
    syncopation: f64,
}

impl RacingTraits {
    fn from_input(input: &GenerateInput) -> Self {
        Self {
            energy: input.energy.clamp(0.0, 1.0),
            complexity: input.complexity.clamp(0.0, 1.0),
            brightness: input.brightness.clamp(0.0, 1.0),
            syncopation: input.syncopation.clamp(0.0, 1.0),
        }
    }

    /// Signed energy deviation from neutral (-0.5..=0.5).
    fn energy_dev(self) -> f64 {
        self.energy - 0.5
    }
}

/// The comfortable register ceiling for a Racing style: bright voices (chip,
/// supersaw, glass) fold lower so they do not shriek; warm voices may sit a
/// little higher. Matches the Extended arrangement's own lead window.
fn racing_register_ceiling(style: Style) -> u8 {
    match style {
        Style::Neon | Style::Chip => 76,
        Style::Fusion | Style::Funk => 79,
    }
}

/// Racing's layer ordering, bed to colour. The bass is the continuous bed
/// (rank 0, never masked); harmony is the pad, the kit the rhythm, the melody
/// the lead, and lift/sparkle the upper colour.
fn racing_layer_rank(event: &MusicEvent) -> u8 {
    match event {
        MusicEvent::Note { lane, .. } => {
            if lane.ends_with("-bass") {
                0
            } else if lane.ends_with("-harmony") {
                1
            } else if lane.ends_with("-melody") {
                3
            } else if lane.ends_with("-lift") || lane.ends_with("-sparkle") {
                4
            } else {
                2
            }
        }
        MusicEvent::Percussion { .. } => 2,
    }
}

/// The development arc shape for a Racing role, mirroring Suspense's own
/// role → arc mapping. Racing has no Bridge or Break role.
fn racing_arc_for_role(role: RacingPhaseRole) -> &'static [u8] {
    match role {
        RacingPhaseRole::Peak | RacingPhaseRole::Build => &[1, 2, 3, 4],
        RacingPhaseRole::Groove => &[2, 3, 4, 3],
        RacingPhaseRole::Intro | RacingPhaseRole::Outro => &[1, 2, 4, 3],
    }
}

/// The composed development arc: layers enter and leave across a phase's
/// blocks instead of holding one texture for the whole length. The bed (bass,
/// rank 0) stays continuous and the closing bar is left intact so the seam
/// still resolves. A seeded density push lets the take thin or fill a block,
/// so density follows the traits rather than only the role.
///
/// The `complexity` trait (0..1) then biases the schedule: high complexity
/// keeps more layers audible (later blocks climb a rank), low complexity thins
/// them. The first block is left untouched so the melody still waits for the
/// build at every complexity.
fn apply_racing_development_arc(section: &mut PortableSection, bar: u32, seed: u32, complexity: f64) {
    if bar == 0 {
        return;
    }
    let Some(spec) = racing_phase_spec(&section.id) else {
        return;
    };
    let bars = section.length_ticks / bar;
    let arc = racing_arc_for_role(spec.role);
    let Some((block_bars, schedule)) = development_schedule(arc, bars) else {
        return;
    };
    let mut rng = DeterministicRandom::new(seed ^ hash_text(&format!("{}:arc", section.id)));
    let mut schedule = schedule;
    for rank in &mut schedule {
        match rng.integer(3) {
            0 => *rank = rank.saturating_sub(1).max(1),
            2 => *rank = (*rank + 1).min(4),
            _ => {}
        }
    }
    // complexity → arc layer count: a one-rank bias applied to every block after
    // the first. The bed (rank 0) is never masked and the first block keeps its
    // rank, so the melody still waits for the build.
    let bias: i32 = if complexity >= 0.62 {
        1
    } else if complexity < 0.4 {
        -1
    } else {
        0
    };
    if bias != 0 {
        for (index, rank) in schedule.iter_mut().enumerate() {
            if index == 0 {
                continue;
            }
            *rank = ((i32::from(*rank)) + bias).clamp(1, 4) as u8;
        }
    }
    let block_ticks = bar * block_bars;
    mask_to_schedule(section, bar, block_ticks, &schedule, racing_layer_rank);
    section.events.sort_by_key(MusicEvent::start_tick);
}

/// The seam vocabulary: how one composed phase hands the music to the next.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum RacingSeamGesture {
    /// Percussion run rising into the downbeat.
    Fill,
    /// Reverse-cymbal swell across the join.
    Riser,
    /// Short melodic pickup from Racing's own progression.
    Lift,
    /// A swell plus a melodic pickup: both carriers.
    Both,
    /// A long quiet low note: the bed fades out instead of hitting.
    Tail,
}

fn racing_seam_lane(event: &MusicEvent) -> &str {
    match event {
        MusicEvent::Note { lane, .. } | MusicEvent::Percussion { lane, .. } => lane,
    }
}

#[allow(clippy::too_many_arguments)]
fn push_racing_seam_note(
    events: &mut Vec<MusicEvent>,
    serial: &mut usize,
    section: &str,
    start: u32,
    duration: u32,
    velocity: f64,
    pitch: u8,
    voice: &str,
) {
    let index = *serial;
    *serial += 1;
    events.push(MusicEvent::Note {
        id: format!("{section}:seam-note:{index}"),
        section: section.to_string(),
        lane: format!("{section}-seam"),
        start_tick: start,
        duration_ticks: duration.max(1),
        velocity: velocity.clamp(0.08, 0.4),
        pitch,
        voice: voice.to_string(),
        role: None,
    });
}

fn push_racing_seam_perc(
    events: &mut Vec<MusicEvent>,
    serial: &mut usize,
    section: &str,
    start: u32,
    duration: u32,
    velocity: f64,
    voice: &str,
) {
    let index = *serial;
    *serial += 1;
    events.push(MusicEvent::Percussion {
        id: format!("{section}:seam-perc:{index}"),
        section: section.to_string(),
        lane: format!("{section}-seam"),
        start_tick: start,
        duration_ticks: duration.max(1),
        velocity: velocity.clamp(0.08, 0.3),
        voice: voice.to_string(),
    });
}

/// A seam note on Racing's own harmony: `base` is the register root (60 = lead,
/// 48 = pad) and `degree` is a progression degree from the shared DNA.
fn racing_seam_pitch(root: &RacingHarmony, degree: i32, base: i32) -> u8 {
    let p = scale_pitch(base + root.root_pitch_class, degree, &root.scale_intervals);
    p.clamp(0, 127) as u8
}

/// Plan every join of the chosen form. A pool section is reusable and built on
/// its own, so the treatment lives here: from the chosen form, join by join,
/// the gesture, its length and its carrier follow the seed and the two phases
/// it connects. Melodic carriers come from Racing's own root/progression, never
/// Suspense's `arc_entry`/aeolian; the shared pitch class is guaranteed by the
/// [`anchor_racing_edges`] pass rather than by this gesture.
fn apply_racing_transition_pass(score: &mut PortableScore, root: &RacingHarmony, seed: u32) {
    let bar = score.bar_ticks();
    if bar == 0 {
        return;
    }
    let Some(form) = score.form.clone() else {
        return;
    };
    let mut pairs: Vec<(String, String)> = form
        .steps
        .windows(2)
        .map(|window| (window[0].section.clone(), window[1].section.clone()))
        .collect();
    if let (Some(loop_from), Some(last)) = (form.loop_from, form.steps.last()) {
        if let Some(first) = form.steps.get(loop_from as usize) {
            pairs.push((last.section.clone(), first.section.clone()));
        }
    }
    // A section can appear in more than one join; the last planned treatment
    // wins, so clear the previous one first.
    for section in &mut score.sections {
        section
            .events
            .retain(|event| !racing_seam_lane(event).ends_with("-seam"));
    }
    let mut serial = 0usize;
    for (out_id, in_id) in pairs {
        let out_role = racing_phase_spec(&out_id).map(|spec| spec.role);
        let in_role = racing_phase_spec(&in_id).map(|spec| spec.role);
        let mut rng =
            DeterministicRandom::new(seed ^ hash_text(&format!("{out_id}>{in_id}:seam")));
        // Different joins get different resources: what is arriving and what is
        // leaving steer the vocabulary.
        let choices: &[RacingSeamGesture] = if in_role == Some(RacingPhaseRole::Peak) {
            &[
                RacingSeamGesture::Fill,
                RacingSeamGesture::Riser,
                RacingSeamGesture::Both,
            ]
        } else if out_role == Some(RacingPhaseRole::Peak) {
            &[
                RacingSeamGesture::Riser,
                RacingSeamGesture::Tail,
                RacingSeamGesture::Both,
                RacingSeamGesture::Fill,
            ]
        } else {
            &[
                RacingSeamGesture::Fill,
                RacingSeamGesture::Riser,
                RacingSeamGesture::Lift,
                RacingSeamGesture::Both,
                RacingSeamGesture::Tail,
            ]
        };
        let gesture = choices[rng.integer(choices.len() as u32) as usize];
        // Long, short or very short: the join decides.
        let span = match rng.integer(3) {
            0 => bar,
            1 => bar * 2,
            _ => bar / 2,
        };
        let landing = rng.integer(3);
        let Some(out_len) = score.section(&out_id).map(|section| section.length_ticks) else {
            continue;
        };
        let out_span = span.min(out_len).max(bar / 4);
        let out_start = out_len.saturating_sub(out_span);
        let mut out_events: Vec<MusicEvent> = Vec::new();
        let mut in_events: Vec<MusicEvent> = Vec::new();
        match gesture {
            RacingSeamGesture::Fill => {
                for (index, step) in [8u32, 10, 12, 14, 15].iter().enumerate() {
                    let offset = (step * bar / 16).min(out_span.saturating_sub(bar / 16));
                    push_racing_seam_perc(
                        &mut out_events,
                        &mut serial,
                        &out_id,
                        out_start + offset,
                        bar / 16,
                        0.12 + 0.015 * index as f64,
                        "tom",
                    );
                }
            }
            RacingSeamGesture::Riser => {
                push_racing_seam_perc(
                    &mut out_events,
                    &mut serial,
                    &out_id,
                    out_start,
                    out_span,
                    0.12,
                    "reverse-cymbal",
                );
            }
            RacingSeamGesture::Lift => {
                for index in 0..3usize {
                    let degree = root.progression_degrees[index % root.progression_degrees.len()];
                    let offset = (index as u32 * out_span / 3)
                        .min(out_span.saturating_sub(bar / 4));
                    push_racing_seam_note(
                        &mut out_events,
                        &mut serial,
                        &out_id,
                        out_start + offset,
                        bar / 4,
                        0.12,
                        racing_seam_pitch(root, degree, 60),
                        "pluck",
                    );
                }
            }
            RacingSeamGesture::Both => {
                push_racing_seam_perc(
                    &mut out_events,
                    &mut serial,
                    &out_id,
                    out_start,
                    out_span,
                    0.12,
                    "reverse-cymbal",
                );
                for index in 0..3usize {
                    let degree = root.progression_degrees[index % root.progression_degrees.len()];
                    let offset = (index as u32 * out_span / 3)
                        .min(out_span.saturating_sub(bar / 4));
                    push_racing_seam_note(
                        &mut out_events,
                        &mut serial,
                        &out_id,
                        out_start + offset,
                        bar / 4,
                        0.12,
                        racing_seam_pitch(root, degree, 60),
                        "pulse",
                    );
                }
            }
            RacingSeamGesture::Tail => {
                let degree = root.progression_degrees[0];
                push_racing_seam_note(
                    &mut out_events,
                    &mut serial,
                    &out_id,
                    out_start,
                    out_span,
                    0.1,
                    racing_seam_pitch(root, degree, 48),
                    "warm",
                );
            }
        }
        match landing {
            1 => push_racing_seam_perc(
                &mut in_events,
                &mut serial,
                &in_id,
                0,
                bar / 8,
                0.12,
                "air-impact",
            ),
            2 => push_racing_seam_perc(&mut in_events, &mut serial, &in_id, 0, bar / 8, 0.22, "kick"),
            _ => {}
        }
        if !out_events.is_empty() {
            if let Some(section) = score.sections.iter_mut().find(|s| s.id == out_id) {
                section.events.extend(out_events);
                section.events.sort_by_key(MusicEvent::start_tick);
            }
        }
        if !in_events.is_empty() {
            if let Some(section) = score.sections.iter_mut().find(|s| s.id == in_id) {
                section.events.extend(in_events);
                section.events.sort_by_key(MusicEvent::start_tick);
            }
        }
    }
}

/// Whether a pitch class sounds within `[start, end)` of a section.
fn racing_bar_has_pc(section: &PortableSection, start: u32, end: u32, pc: u8) -> bool {
    section.events.iter().any(|event| match event {
        MusicEvent::Note {
            start_tick,
            duration_ticks,
            pitch,
            ..
        } => *start_tick < end && start_tick + duration_ticks > start && pitch % 12 == pc % 12,
        _ => false,
    })
}

/// Give every composed section a shared pitch class in its first and last bar:
/// a soft tonic anchor on Racing's own root pitch class, so any legal join
/// shares a pitch class by construction. The register pass keeps the anchor
/// inside the comfortable band.
fn anchor_racing_edges(section: &mut PortableSection, root_pc: i32, bar: u32) {
    if section.length_ticks == 0 || bar == 0 {
        return;
    }
    let root_note = (60 + root_pc).clamp(0, 127) as u8;
    let head_end = bar.min(section.length_ticks);
    let last_start = section.length_ticks.saturating_sub(bar);
    let mut anchors: Vec<(u32, u32)> = Vec::new();
    if !racing_bar_has_pc(section, 0, head_end, root_note % 12) {
        anchors.push((0, head_end));
    }
    if last_start > 0
        && !racing_bar_has_pc(section, last_start, section.length_ticks, root_note % 12)
    {
        anchors.push((last_start, section.length_ticks - last_start));
    }
    if anchors.is_empty() {
        return;
    }
    let id = section.id.clone();
    for (index, (start, duration)) in anchors.into_iter().enumerate() {
        section.events.push(MusicEvent::Note {
            id: format!("{id}:anchor:{index}"),
            section: id.clone(),
            lane: format!("{id}-anchor"),
            start_tick: start,
            duration_ticks: duration.max(1),
            velocity: 0.12,
            pitch: root_note,
            voice: "warm".to_string(),
            role: None,
        });
    }
    section.events.sort_by_key(MusicEvent::start_tick);
}

/// Fold a composed section's piercing highs down whole octaves (pitch class, and
/// hence the harmony, are preserved) so a composed Racing run never squeals
/// over the rest of the mix.
fn apply_racing_register_ceiling(section: &mut PortableSection, ceiling: u8) {
    for event in &mut section.events {
        if let MusicEvent::Note { pitch, .. } = event {
            let mut value = i32::from(*pitch);
            while value > i32::from(ceiling) {
                value -= 12;
            }
            *pitch = u8::try_from(value.max(0)).unwrap_or(*pitch);
        }
    }
}

/// The continuous trait surface for a composed Racing section: each trait drives
/// a concrete, monotonic parameter on top of the already-generated material.
///
/// - `energy` scales every lane's velocity and adds kit density (extra hats on
///   empty sixteenths);
/// - `complexity` adds passing melody onsets (copied in-mode pitches on empty
///   eighth-grid positions);
/// - `syncopation` displaces a share of even-eighth melody onsets by a sixteenth.
///
/// `brightness` is deliberately absent: the base generator already maps it to
/// mode, melody octave and timbre, and the composed path inherits that material.
fn apply_racing_trait_surface(section: &mut PortableSection, bar: u32, traits: &RacingTraits) {
    if bar == 0 {
        return;
    }
    let pulse = bar / 8;
    let sixteenth = pulse / 2;
    let id = section.id.clone();
    let mut serial = 0usize;

    // energy → lane velocities (continuous, monotonic).
    let vel_scale = (0.75 + traits.energy * 0.5).clamp(0.6, 1.4);
    for event in &mut section.events {
        match event {
            MusicEvent::Note { velocity, .. } | MusicEvent::Percussion { velocity, .. } => {
                *velocity = (*velocity * vel_scale).clamp(0.08, 0.96);
            }
        }
    }

    // energy → kit density: extra hats on empty sixteenths, count grows with the
    // knob.
    let extra_kit = (traits.energy * 4.0).round() as usize;
    if extra_kit > 0 {
        let mut placed = 0usize;
        for start in (0..section.length_ticks).step_by(sixteenth as usize) {
            if start % pulse == 0 || start + sixteenth > section.length_ticks {
                continue;
            }
            if section
                .events
                .iter()
                .any(|e| matches!(e, MusicEvent::Percussion { start_tick, .. } if *start_tick == start))
            {
                continue;
            }
            section.events.push(MusicEvent::Percussion {
                id: format!("{id}:trait:kit:{serial}"),
                section: id.clone(),
                lane: format!("{id}-kit"),
                start_tick: start,
                duration_ticks: sixteenth,
                velocity: 0.14,
                voice: "hat".to_string(),
            });
            serial += 1;
            placed += 1;
            if placed >= extra_kit {
                break;
            }
        }
    }

    // complexity → passing melody onsets: copy an in-mode pitch onto an empty
    // eighth-grid slot. Count grows with the knob. Placement starts after the
    // first phrase so the melody still waits for the build (the arc's contract).
    let passing = if traits.complexity > 0.5 {
        ((traits.complexity - 0.5) * 8.0).round() as usize
    } else {
        0
    };
    if passing > 0 {
        let pitches: Vec<u8> = section
            .events
            .iter()
            .filter(|e| e.is_melody())
            .filter_map(MusicEvent::pitch)
            .collect();
        let mut placed = 0usize;
        for start in (bar * 4..section.length_ticks).step_by(pulse as usize) {
            if start + pulse > section.length_ticks {
                continue;
            }
            if section
                .events
                .iter()
                .any(|e| e.start_tick() == start)
            {
                continue;
            }
            let Some(&pitch) = pitches.get(placed % pitches.len().max(1)) else {
                continue;
            };
            section.events.push(MusicEvent::Note {
                id: format!("{id}:trait:mel:{serial}"),
                section: id.clone(),
                lane: format!("{id}-melody"),
                start_tick: start,
                duration_ticks: pulse,
                velocity: 0.2,
                pitch,
                voice: "pluck".to_string(),
                role: Some("melody".to_string()),
            });
            serial += 1;
            placed += 1;
            if placed >= passing {
                break;
            }
        }
    }

    // syncopation → rhythmic displacement: a share of even-eighth melody onsets
    // move a sixteenth later, off the grid. Count grows with the knob.
    let displace = (traits.syncopation * 4.0).round() as usize;
    if displace > 0 {
        let mut displaced = 0usize;
        for event in &mut section.events {
            let MusicEvent::Note {
                start_tick,
                duration_ticks,
                velocity,
                role,
                ..
            } = event
            else {
                continue;
            };
            if role.as_deref() != Some("melody") {
                continue;
            }
            if *start_tick % pulse != 0 || !(*start_tick / pulse).is_multiple_of(2) {
                continue;
            }
            // Never move the downbeat of a bar or the closing bar's arrivals.
            if *start_tick % bar == 0 || *start_tick + bar >= section.length_ticks {
                continue;
            }
            if *start_tick + sixteenth + *duration_ticks > section.length_ticks {
                continue;
            }
            *start_tick += sixteenth;
            // A pushed onset reads as a soft anticipation, not a stray high blip:
            // halve its velocity so it never outshines the on-grid note it leads
            // into. The register pass below still keeps the pitch under the
            // ceiling, so the pair stays quiet and in-band.
            *velocity = (*velocity * 0.5).clamp(0.08, 0.96);
            displaced += 1;
            if displaced >= displace {
                break;
            }
        }
    }

    section.events.sort_by_key(MusicEvent::start_tick);
}

/// Re-time a four-bar Racing section to `bars` by tiling its authored block.
/// Every event keeps its lane, voice, pitch and role; only its id and onset
/// change, so the score stays valid and every event id stays unique.
fn retime_section(section: &mut PortableSection, bars: u32, bar_ticks: u32) {
    let src_len = section.length_ticks;
    if src_len == 0 {
        return;
    }
    let target = bars * bar_ticks;
    let src_events = std::mem::take(&mut section.events);
    let mut out = Vec::new();
    let mut block = 0u32;
    while block * src_len < target {
        let offset = block * src_len;
        for event in &src_events {
            let start = event.start_tick() + offset;
            if start >= target {
                continue;
            }
            let dur = event.duration_ticks().min(target - start);
            let mut event = event.clone();
            match &mut event {
                MusicEvent::Note {
                    id,
                    start_tick,
                    duration_ticks,
                    ..
                }
                | MusicEvent::Percussion {
                    id,
                    start_tick,
                    duration_ticks,
                    ..
                } => {
                    *id = format!("{id}:t{block}");
                    *start_tick = start;
                    *duration_ticks = dur;
                }
            }
            out.push(event);
        }
        block += 1;
    }
    section.events = out;
    section.length_ticks = target;
}

