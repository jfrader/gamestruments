    /// Pitch classes sounding in a section's first or last bar.
    fn bar_pitch_classes(section: &PortableSection, bar: u32, first: bool) -> [bool; 12] {
        let mut set = [false; 12];
        let start = if first {
            0
        } else {
            section.length_ticks.saturating_sub(bar)
        };
        let end = if first { bar } else { section.length_ticks };
        for event in &section.events {
            if let MusicEvent::Note {
                start_tick,
                duration_ticks,
                pitch,
                ..
            } = event
            {
                let end_tick = start_tick + duration_ticks;
                if *start_tick < end && end_tick > start {
                    set[(*pitch % 12) as usize] = true;
                }
            }
        }
        set
    }

    #[test]
    fn composed_development_arc_varies_layers_across_blocks() {
        for style in [Style::Fusion, Style::Neon, Style::Funk, Style::Chip] {
            let input = lab_input(style, "level-001");
            let score =
                generate_racing_arrangement(&input, RacingArrangement::Seeded).expect("composed");
            let bar = score.bar_ticks();
            for nid in ["attack", "final-lap"] {
                let sec = score.section(nid).expect(nid);
                let bars = sec.length_ticks / bar;
                let block_bars = if bars <= 8 { 2 } else { 4 };
                let blocks = (bars / block_bars) as usize;
                assert!(blocks >= 2, "{style:?} {nid} needs blocks to develop");
                let block_ticks = bar * block_bars;

                // The bed (bass, rank 0) stays continuous in every block.
                for block in 0..blocks {
                    let from = block as u32 * block_ticks;
                    let to = from + block_ticks;
                    let has_bass = sec.events.iter().any(|event| {
                        matches!(event, MusicEvent::Note { lane, .. } if lane.ends_with("-bass"))
                            && event.start_tick() >= from
                            && event.start_tick() < to
                    });
                    assert!(
                        has_bass,
                        "{style:?} {nid} block {block} lost the bass bed"
                    );
                }

                // The melody enters later: it is masked from the first block and
                // present in a later one, so the phase develops instead of holding
                // one texture the whole length.
                let melody_in = |from: u32, to: u32| {
                    sec.events.iter().any(|event| {
                        matches!(event, MusicEvent::Note { lane, .. } if lane.ends_with("-melody"))
                            && event.start_tick() >= from
                            && event.start_tick() < to
                    })
                };
                assert!(
                    !melody_in(0, block_ticks),
                    "{style:?} {nid} melody must wait for the build"
                );
                assert!(
                    (1..blocks as u32).any(|block| melody_in(block * block_ticks, (block + 1) * block_ticks)),
                    "{style:?} {nid} melody never enters"
                );
            }
        }
    }

